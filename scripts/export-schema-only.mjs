/**
 * Eksportuje schemat tabel (public) do pliku SQL — bez danych.
 * Użycie: node scripts/export-schema-only.mjs [ścieżka-wyjścia]
 */
import fs from 'fs'
import { dirname, join, resolve } from 'path'
import { fileURLToPath } from 'url'
import postgres from 'postgres'

const __dirname = dirname(fileURLToPath(import.meta.url))

function loadEnvLocal() {
  const p = join(__dirname, '..', '.env.local')
  if (!fs.existsSync(p)) return
  for (const line of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const i = t.indexOf('=')
    if (i === -1) continue
    const key = t.slice(0, i).trim()
    let val = t.slice(i + 1).trim()
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1)
    }
    if (key === 'DATABASE_URL' && !process.env.DATABASE_URL) {
      process.env.DATABASE_URL = val
    }
  }
}

loadEnvLocal()

const outPath =
  process.argv[2] ||
  resolve(__dirname, '..', '..', 'baza danych velorace', 'velorace-schema.sql')

if (!process.env.DATABASE_URL) {
  console.error('Brak DATABASE_URL')
  process.exit(1)
}

const sql = postgres(process.env.DATABASE_URL, { max: 1, idle_timeout: 5, connect_timeout: 20 })

function qIdent(name) {
  return `"${String(name).replace(/"/g, '""')}"`
}

function formatDefault(def) {
  if (def == null) return null
  return String(def)
}

async function main() {
  const tables = await sql`
    SELECT c.relname AS name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind = 'r'
    ORDER BY c.relname
  `

  const extensions = await sql`
    SELECT extname FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY extname
  `

  const lines = []
  lines.push('-- Velorace — schemat tabel (bez danych)')
  lines.push(`-- Wygenerowano: ${new Date().toISOString()}`)
  lines.push('-- Odtwórz na pustej bazie PostgreSQL (inna instancja / inny adres OK).')
  lines.push('-- Nie zawiera danych ani ról użytkowników.')
  lines.push('')

  for (const ext of extensions) {
    lines.push(`CREATE EXTENSION IF NOT EXISTS ${qIdent(ext.extname)};`)
  }
  if (extensions.length) lines.push('')

  // Enum types
  const enums = await sql`
    SELECT t.typname AS name,
           array_agg(e.enumlabel ORDER BY e.enumsortorder) AS labels
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
    GROUP BY t.typname
    ORDER BY t.typname
  `
  for (const en of enums) {
    const labels = en.labels.map(l => `'${String(l).replace(/'/g, "''")}'`).join(', ')
    lines.push(`DO $$ BEGIN`)
    lines.push(`  CREATE TYPE ${qIdent(en.name)} AS ENUM (${labels});`)
    lines.push(`EXCEPTION WHEN duplicate_object THEN NULL; END $$;`)
    lines.push('')
  }

  for (const t of tables) {
    const table = t.name
    const cols = await sql`
      SELECT
        a.attname AS name,
        pg_catalog.format_type(a.atttypid, a.atttypmod) AS type,
        a.attnotnull AS not_null,
        pg_get_expr(ad.adbin, ad.adrelid) AS default_expr,
        a.attidentity AS identity,
        a.attgenerated AS generated,
        col_description(a.attrelid, a.attnum) AS comment
      FROM pg_attribute a
      LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
      WHERE a.attrelid = ${`public.${table}`}::regclass
        AND a.attnum > 0
        AND NOT a.attisdropped
      ORDER BY a.attnum
    `

    const colDefs = []
    for (const c of cols) {
      let def = `  ${qIdent(c.name)} ${c.type}`
      if (c.identity === 'a') def += ' GENERATED ALWAYS AS IDENTITY'
      else if (c.identity === 'd') def += ' GENERATED BY DEFAULT AS IDENTITY'
      else if (c.generated === 's' && c.default_expr) {
        def += ` GENERATED ALWAYS AS (${c.default_expr}) STORED`
      } else if (c.default_expr) {
        def += ` DEFAULT ${formatDefault(c.default_expr)}`
      }
      if (c.not_null && c.identity === '') def += ' NOT NULL'
      colDefs.push(def)
    }

    // Primary key / unique / check constraints attached to table
    const cons = await sql`
      SELECT con.conname AS name,
             con.contype AS type,
             pg_get_constraintdef(con.oid, true) AS def
      FROM pg_constraint con
      JOIN pg_class rel ON rel.oid = con.conrelid
      JOIN pg_namespace n ON n.oid = rel.relnamespace
      WHERE n.nspname = 'public'
        AND rel.relname = ${table}
        AND con.contype IN ('p', 'u', 'c')
      ORDER BY con.contype, con.conname
    `
    for (const c of cons) {
      colDefs.push(`  CONSTRAINT ${qIdent(c.name)} ${c.def}`)
    }

    lines.push(`CREATE TABLE IF NOT EXISTS ${qIdent(table)} (`)
    lines.push(colDefs.join(',\n'))
    lines.push(`);`)
    lines.push('')
  }

  // Foreign keys (after all tables)
  lines.push('-- ── Foreign keys ──────────────────────────────────────────')
  const fks = await sql`
    SELECT
      rel.relname AS table_name,
      con.conname AS name,
      pg_get_constraintdef(con.oid, true) AS def
    FROM pg_constraint con
    JOIN pg_class rel ON rel.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = rel.relnamespace
    WHERE n.nspname = 'public'
      AND con.contype = 'f'
    ORDER BY rel.relname, con.conname
  `
  for (const fk of fks) {
    lines.push(
      `ALTER TABLE ${qIdent(fk.table_name)} DROP CONSTRAINT IF EXISTS ${qIdent(fk.name)};`,
    )
    lines.push(
      `ALTER TABLE ${qIdent(fk.table_name)} ADD CONSTRAINT ${qIdent(fk.name)} ${fk.def};`,
    )
  }
  lines.push('')

  // Indexes (non-constraint)
  lines.push('-- ── Indexes ───────────────────────────────────────────────')
  const indexes = await sql`
    SELECT
      c.relname AS index_name,
      t.relname AS table_name,
      pg_get_indexdef(i.indexrelid) AS def
    FROM pg_index i
    JOIN pg_class c ON c.oid = i.indexrelid
    JOIN pg_class t ON t.oid = i.indrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = 'public'
      AND NOT i.indisprimary
      AND NOT i.indisexclusion
      AND c.relkind = 'i'
      AND NOT EXISTS (
        SELECT 1 FROM pg_constraint con
        WHERE con.conindid = i.indexrelid AND con.contype IN ('u', 'p')
      )
    ORDER BY t.relname, c.relname
  `
  for (const idx of indexes) {
    // pg_get_indexdef already has CREATE INDEX ...
    const def = String(idx.def)
    if (/^CREATE /i.test(def)) {
      lines.push(def.replace(/^CREATE (UNIQUE )?INDEX /i, 'CREATE $1INDEX IF NOT EXISTS ') + ';')
    } else {
      lines.push(def + ';')
    }
  }
  lines.push('')

  // Sequences owned (usually covered by identity); ensure serial sequences exist — skip if identity

  fs.mkdirSync(dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, lines.join('\n'), 'utf8')

  const readme = join(dirname(outPath), 'README.md')
  fs.writeFileSync(
    readme,
    [
      '# Velorace — schemat bazy (tylko tabele)',
      '',
      'Plik `velorace-schema.sql` zawiera **struktury tabel** (CREATE TABLE, FK, indeksy, typy ENUM, extensions).',
      '**Bez danych** i bez użytkowników/ról.',
      '',
      '## Odtworzenie na nowej instancji',
      '',
      '1. Utwórz pustą bazę PostgreSQL (dowolny host/adres).',
      '2. Ustaw `DATABASE_URL` na nową instancję.',
      '3. Uruchom:',
      '',
      '```bash',
      'psql "$DATABASE_URL" -f velorace-schema.sql',
      '```',
      '',
      'Albo w Cursorze: wklej zawartość `velorace-schema.sql` i poproś o wykonanie na docelowej bazie.',
      '',
      `Wygenerowano: ${new Date().toISOString()}`,
      '',
    ].join('\n'),
    'utf8',
  )

  console.log(`OK: ${tables.length} tabel → ${outPath}`)
  await sql.end({ timeout: 5 })
}

main().catch(async e => {
  console.error(e)
  try {
    await sql.end({ timeout: 2 })
  } catch {}
  process.exit(1)
})
